import AppKit
import ApplicationServices
import Foundation

/// Preserves and restores all pasteboard representations in exact writer order.
enum PasteboardSnapshot {
    typealias ItemSnapshot = [(type: NSPasteboard.PasteboardType, data: Data)]

    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    static func capture(from pasteboard: NSPasteboard) -> [ItemSnapshot] {
        guard let items = pasteboard.pasteboardItems else { return [] }
        return items.compactMap { item in
            let reps: ItemSnapshot = item.types.compactMap { type in
                guard let data = item.data(forType: type) else { return nil }
                return (type, data)
            }
            return reps.isEmpty ? nil : reps
        }
    }

    static func restore(_ snapshots: [ItemSnapshot], to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !snapshots.isEmpty else { return }
        let items: [NSPasteboardItem] = snapshots.map { reps in
            let item = NSPasteboardItem()
            for (type, data) in reps {
                item.setData(data, forType: type)
            }
            return item
        }
        pasteboard.writeObjects(items)
    }

    /// Creates a pasteboard item tagged with nspasteboard.org markers so clipboard managers ignore it.
    static func makeTransientStringItem(_ text: String) -> NSPasteboardItem {
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: transientType)
        item.setData(Data(), forType: concealedType)
        item.setData(Data(), forType: autoGeneratedType)
        return item
    }
}

/// Injects selected cognitive card prompts back into the host application.
/// Adapted from Cotabby's SuggestionInserter:
/// - Writes transient/concealed pasteboard item so clipboard managers skip it.
/// - Prefers pressing the host app's real `Edit > Paste` menu item via Accessibility (bypasses IME & Chromium modifier bugs).
/// - Falls back to annotated-session synthetic Cmd+V.
/// - Restores the user's full clipboard after 300ms unless newer user clipboard activity wins.
@MainActor
final class TextInjector {
    private static let pasteboardRestoreDelay: TimeInterval = 0.30
    private var pendingRestore: DispatchWorkItem?
    private var savedClipboard: [PasteboardSnapshot.ItemSnapshot]?
    private var cachedPasteMenuItems: [pid_t: AXUIElement] = [:]

    private static let prePasteKeySettleDelay: TimeInterval = 0.035

    func inject(card: CardItem, mode: InjectMode, context: CapturedContext) {
        let textToInsert: String
        var didPostSelectionKey = false

        switch mode {
        case .append:
            textToInsert = card.prompt.replacingOccurrences(of: "{{input}}", with: "")
            // If the user originally highlighted text, collapse selection to the end before appending.
            if context.captureScope == .selection {
                postKey(virtualKey: 124, flags: []) // Right arrow
                didPostSelectionKey = true
            }
        case .wrap:
            if card.prompt.contains("{{input}}") {
                textToInsert = card.prompt.replacingOccurrences(of: "{{input}}", with: context.inputText)
            } else {
                textToInsert = context.inputText + card.prompt
            }
            // Select the original span so Paste replaces it cleanly.
            switch context.captureScope {
            case .selection:
                break // Still selected
            case .paragraph:
                postKey(virtualKey: 126, flags: [.maskCommand, .maskShift])
                didPostSelectionKey = true
            case .fullField:
                postKey(virtualKey: 0, flags: .maskCommand)
                didPostSelectionKey = true
            }
        }

        if didPostSelectionKey {
            // Give Electron/browser hosts a brief settle window so the selection/caret move
            // finishes before Edit > Paste fires.
            DispatchQueue.main.asyncAfter(deadline: .now() + Self.prePasteKeySettleDelay) { [weak self] in
                self?.pasteViaClipboard(textToInsert, targetPID: context.appPID)
            }
        } else {
            pasteViaClipboard(textToInsert, targetPID: context.appPID)
        }
    }

    private func pasteViaClipboard(_ text: String, targetPID: pid_t) {
        let pasteboard = NSPasteboard.general
        if pendingRestore == nil {
            savedClipboard = PasteboardSnapshot.capture(from: pasteboard)
        }
        let saved = savedClipboard ?? []

        pasteboard.clearContents()
        guard pasteboard.writeObjects([PasteboardSnapshot.makeTransientStringItem(text)]) else {
            pendingRestore?.cancel()
            PasteboardSnapshot.restore(saved, to: pasteboard)
            pendingRestore = nil
            savedClipboard = nil
            return
        }
        let expectedChangeCount = pasteboard.changeCount

        if !pressPasteMenuItem(for: targetPID) {
            postKey(virtualKey: 9, flags: .maskCommand) // Cmd + V
        }

        pendingRestore?.cancel()
        let restoreWork = DispatchWorkItem { [weak self] in
            guard let self else { return }
            if pasteboard.changeCount == expectedChangeCount {
                PasteboardSnapshot.restore(saved, to: pasteboard)
            }
            self.pendingRestore = nil
            self.savedClipboard = nil
        }
        pendingRestore = restoreWork
        DispatchQueue.main.asyncAfter(deadline: .now() + Self.pasteboardRestoreDelay, execute: restoreWork)
    }

    private func pressPasteMenuItem(for pid: pid_t) -> Bool {
        if let cached = cachedPasteMenuItems[pid] {
            if AXUIElementPerformAction(cached, kAXPressAction as CFString) == .success {
                return true
            }
            cachedPasteMenuItems.removeValue(forKey: pid)
        }

        guard let menuItem = findPasteMenuItem(for: pid) else { return false }
        if AXUIElementPerformAction(menuItem, kAXPressAction as CFString) == .success {
            cachedPasteMenuItems[pid] = menuItem
            return true
        }
        return false
    }

    private func findPasteMenuItem(for pid: pid_t) -> AXUIElement? {
        let appElement = AXUIElementCreateApplication(pid)
        var menuBarRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(appElement, kAXMenuBarAttribute as CFString, &menuBarRef) == .success,
              let menuBar = menuBarRef else {
            return nil
        }

        var topItemsRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(menuBar as! AXUIElement, kAXChildrenAttribute as CFString, &topItemsRef) == .success,
              let topItems = topItemsRef as? [AXUIElement] else {
            return nil
        }

        for menuBarItem in topItems {
            var subMenusRef: CFTypeRef?
            guard AXUIElementCopyAttributeValue(menuBarItem, kAXChildrenAttribute as CFString, &subMenusRef) == .success,
                  let subMenus = subMenusRef as? [AXUIElement] else {
                continue
            }
            for menu in subMenus {
                var itemsRef: CFTypeRef?
                guard AXUIElementCopyAttributeValue(menu, kAXChildrenAttribute as CFString, &itemsRef) == .success,
                      let items = itemsRef as? [AXUIElement] else {
                    continue
                }
                for item in items {
                    var cmdCharRef: CFTypeRef?
                    var modifiersRef: CFTypeRef?
                    AXUIElementCopyAttributeValue(item, kAXMenuItemCmdCharAttribute as CFString, &cmdCharRef)
                    AXUIElementCopyAttributeValue(item, kAXMenuItemCmdModifiersAttribute as CFString, &modifiersRef)
                    let cmdChar = (cmdCharRef as? String)?.uppercased()
                    let modifiers = (modifiersRef as? Int) ?? 0
                    // kAXMenuItemModifierNoCommand == 8; standard Cmd+V has modifiers == 0 and cmdChar == "V".
                    if cmdChar == "V" && modifiers == 0 {
                        return item
                    }
                }
            }
        }
        return nil
    }

    private func postKey(virtualKey: CGKeyCode, flags: CGEventFlags) {
        let source = CGEventSource(stateID: .combinedSessionState)
        source?.setLocalEventsFilterDuringSuppressionState(
            [.permitLocalMouseEvents, .permitSystemDefinedEvents],
            state: .eventSuppressionStateSuppressionInterval
        )
        guard let down = CGEvent(keyboardEventSource: source, virtualKey: virtualKey, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: virtualKey, keyDown: false) else {
            return
        }
        down.flags = flags
        up.flags = flags
        down.post(tap: .cgAnnotatedSessionEventTap)
        up.post(tap: .cgAnnotatedSessionEventTap)
    }
}
